import { Body, Controller, Headers, Ip, Post } from '@nestjs/common';
import { ApiHeader, ApiOkResponse, ApiOperation, ApiTags } from '@nestjs/swagger';
import type { AuthenticatedUser } from 'src/common/auth/authenticated-user';
import { OptionalUser } from 'src/common/decorators/optional-user.decorator';
import { Public } from 'src/common/decorators/public.decorator';
import { CreateStreamingSessionRequestDto, StreamingSessionViewDto } from './dto/streaming-session.dto';
import { StreamingSessionService } from './streaming-session.service';

/**
 * Public: guests (X-Guest-Key) and members (optional bearer token) share the
 * route, exactly like `GET /episodes/:id/access`. Access itself is re-verified
 * server-side; the token or guest key only says who is asking.
 */
@ApiTags('playback')
@Public()
@Controller('playback')
export class StreamingSessionController {
  constructor(private readonly sessions: StreamingSessionService) {}

  @Post('sessions')
  @ApiOperation({ summary: 'Verify playback access and open a streaming session (flow 3, step 11)' })
  @ApiHeader({
    name: 'X-Guest-Key',
    required: false,
    description: 'UUID v4 generated by the client; required for guests',
  })
  @ApiHeader({ name: 'Idempotency-Key', required: false, description: 'Sending it twice reuses the live session' })
  @ApiOkResponse({ type: StreamingSessionViewDto })
  create(
    @Body() dto: CreateStreamingSessionRequestDto,
    @OptionalUser() user: AuthenticatedUser | undefined,
    // Validated as UUID v4 in StreamingSessionService (400 GUEST_KEY_INVALID).
    @Headers('x-guest-key') guestKey?: string,
    @Ip() ip?: string,
    @Headers('user-agent') userAgent?: string,
  ) {
    return this.sessions.create({
      episodeId: dto.episodeId,
      userId: user?.id,
      guestKey,
      ipAddress: ip,
      userAgent,
    });
  }
}
