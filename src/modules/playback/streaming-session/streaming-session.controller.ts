import { Body, Controller, Get, Header, Headers, Ip, Param, ParseUUIDPipe, Patch, Post, Query } from '@nestjs/common';
import { ApiHeader, ApiOkResponse, ApiOperation, ApiProduces, ApiTags } from '@nestjs/swagger';
import { Throttle } from '@nestjs/throttler';
import type { AuthenticatedUser } from 'src/common/auth/authenticated-user';
import { OptionalUser } from 'src/common/decorators/optional-user.decorator';
import { IdempotencyKey } from 'src/common/decorators/idempotency-key.decorator';
import { Public } from 'src/common/decorators/public.decorator';
import { appConfig } from 'src/config/config.module';
import { StreamingSessionViewDto } from './dto/streaming-session.dto';
import { PlaybackUrlService, type PlaybackToken } from './playback-url.service';
import { StreamingSessionService } from './streaming-session.service';
import { NextEpisodeViewDto } from 'src/modules/playback/streaming-session/dto/next-episode.view.dto';
import { CreateStreamingSessionRequestDto } from 'src/modules/playback/streaming-session/dto/create-streaming-session.request.dto';
import { CompleteSessionRequestDto } from 'src/modules/playback/streaming-session/dto/complete-session.request.dto';
import { HeartbeatRequestDto } from 'src/modules/playback/watch-progress/dto/heart-beat.request.dto';
import { SessionStateViewDto } from 'src/modules/playback/watch-progress/dto/session-state.view.dto';
import { StopSessionRequestDto } from 'src/modules/playback/watch-progress/dto/stop-session.request.dto';

const ID = new ParseUUIDPipe({ version: '4' });

// Mobile carriers put many viewers behind one CGNAT egress IP, so the API-wide per-IP
// budget starves a beating player. Opening a session is a deliberate tap and stays tight
// to keep guest minting bounded; a heartbeat is ~4–6 requests/min per viewer, so its
// budget is sized for hundreds of viewers per IP (the session's owner key still gates it).
const openSessionRateLimit = {
  default: { limit: () => appConfig().rateLimit.playbackSessionLimit, ttl: () => appConfig().rateLimit.ttlMs },
};
const heartbeatRateLimit = {
  default: { limit: () => appConfig().rateLimit.playbackHeartbeatLimit, ttl: () => appConfig().rateLimit.ttlMs },
};

/**
 * Public: guests (X-Guest-Key) and members (optional bearer token) share the
 * route, exactly like `GET /episodes/:id/access`. Access itself is re-verified
 * server-side; the token or guest key only says who is asking.
 */
@ApiTags('playback')
@Public()
@Controller('playback')
export class StreamingSessionController {
  constructor(
    private readonly sessions: StreamingSessionService,
    private readonly urls: PlaybackUrlService,
  ) {}

  @Throttle(openSessionRateLimit)
  @Post('sessions')
  @ApiOperation({ summary: 'Verify playback access and open a streaming session (flow 3, step 11)' })
  @ApiHeader({
    name: 'X-Guest-Key',
    required: false,
    description: 'UUID v4 generated by the client; required for guests',
  })
  @ApiHeader({
    name: 'X-Device-Id',
    required: false,
    description: 'UUID v4 of the install; required for members (MF-4)',
  })
  @ApiHeader({ name: 'Idempotency-Key', required: false, description: 'Sending it twice reuses the live session' })
  @ApiOkResponse({ type: StreamingSessionViewDto })
  create(
    @Body() dto: CreateStreamingSessionRequestDto,
    @OptionalUser() user: AuthenticatedUser | undefined,
    // Validated as UUID v4 in StreamingSessionService (400 GUEST_KEY_INVALID).
    @Headers('x-guest-key') guestKey?: string,
    @Headers('x-device-id') deviceKey?: string,
    @IdempotencyKey() idempotencyKey?: string,
    @Ip() ip?: string,
    @Headers('user-agent') userAgent?: string,
  ) {
    return this.sessions.create({
      episodeId: dto.episodeId,
      userId: user?.id,
      guestKey,
      device: user && deviceKey ? { key: deviceKey, name: dto.deviceName, platform: dto.devicePlatform } : undefined,
      idempotencyKey,
      ipAddress: ip,
      userAgent,
    });
  }

  /**
   * Token playlist endpoints: players cannot send auth headers, so the signed
   * query (`?s=&exp=&sig=`) is the credential. The session row is re-checked.
   */
  @Get('s/:sessionId/master.m3u8')
  @ApiOperation({ summary: 'Filtered master playlist: only renditions at or below the plan ceiling' })
  @ApiProduces('application/vnd.apple.mpegurl')
  @Header('Content-Type', 'application/vnd.apple.mpegurl')
  // P2-1: ten seconds bounds origin stale-ness while letting the player reuse a rendition switch.
  @Header('Cache-Control', 'private, max-age=10')
  master(
    @Param('sessionId', ID) sessionId: string,
    @Query('s') s: string,
    @Query('exp') exp: string,
    @Query('sig') sig: string,
  ) {
    return this.urls.masterPlaylist(sessionId, tokenOf(s, exp, sig)).then(({ text }) => text);
  }

  @Get('s/:sessionId/renditions/:quality/index.m3u8')
  @ApiOperation({ summary: 'Variant playlist with segments rewritten to signed CDN URLs' })
  @ApiProduces('application/vnd.apple.mpegurl')
  @Header('Content-Type', 'application/vnd.apple.mpegurl')
  @Header('Cache-Control', 'private, max-age=10')
  rendition(
    @Param('sessionId', ID) sessionId: string,
    @Param('quality') quality: string,
    @Query('s') s: string,
    @Query('exp') exp: string,
    @Query('sig') sig: string,
  ) {
    return this.urls.variantPlaylist(sessionId, quality, tokenOf(s, exp, sig));
  }

  @Throttle(heartbeatRateLimit)
  @Patch('sessions/:sessionId/heartbeat')
  @ApiOperation({ summary: 'Keep the session alive and persist the position (flow 3, step 15)' })
  @ApiHeader({ name: 'X-Guest-Key', required: false, description: 'Must match the key the session was opened with' })
  @ApiOkResponse({ type: SessionStateViewDto })
  heartbeat(
    @Param('sessionId', ID) sessionId: string,
    @Body() dto: HeartbeatRequestDto,
    @OptionalUser() user: AuthenticatedUser | undefined,
    @Headers('x-guest-key') guestKey?: string,
  ) {
    return this.sessions.heartbeat(sessionId, { userId: user?.id, guestKey }, dto);
  }

  @Post('sessions/:sessionId/stop')
  @ApiOperation({ summary: 'Viewer stops: save the position and free the slot (flow 3, steps 19/21)' })
  @ApiHeader({ name: 'X-Guest-Key', required: false, description: 'Must match the key the session was opened with' })
  @ApiOkResponse({ type: SessionStateViewDto })
  stop(
    @Param('sessionId', ID) sessionId: string,
    @Body() dto: StopSessionRequestDto,
    @OptionalUser() user: AuthenticatedUser | undefined,
    @Headers('x-guest-key') guestKey?: string,
  ) {
    return this.sessions.stop(sessionId, { userId: user?.id, guestKey }, dto);
  }

  @Post('sessions/:sessionId/complete')
  @ApiOperation({
    summary:
      'Viewer finishes: close the session and mark completed only at the position threshold (flow 3, steps 18/20)',
    description:
      'The episode is marked completed only when the final position reaches episodeCompletionPercent; below it the session closes like a stop. A finish call is not proof of watching.',
  })
  @ApiHeader({ name: 'X-Guest-Key', required: false, description: 'Must match the key the session was opened with' })
  @ApiOkResponse({ type: SessionStateViewDto })
  complete(
    @Param('sessionId', ID) sessionId: string,
    @OptionalUser() user: AuthenticatedUser | undefined,
    @Headers('x-guest-key') guestKey?: string,
    @Body() dto?: CompleteSessionRequestDto,
  ) {
    return this.sessions.complete(sessionId, { userId: user?.id, guestKey }, { positionSeconds: dto?.positionSeconds });
  }

  @Get('episodes/:episodeId/next')
  @ApiOperation({
    summary: 'Episode after this one, if released and not under revision; access still goes through Main Flow 2',
  })
  @ApiOkResponse({ type: NextEpisodeViewDto })
  next(@Param('episodeId', ID) episodeId: string) {
    return this.sessions.nextEpisode(episodeId);
  }
}

function tokenOf(s: string, exp: string, sig: string): PlaybackToken {
  return { sessionId: s, exp: Number(exp), sig: sig ?? '' };
}
